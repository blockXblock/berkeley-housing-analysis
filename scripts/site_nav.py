#!/usr/bin/env python3
"""site_nav.py — the site-wide menu (BerkeleyBuild · Housing · Berkeley · Learn), one block on every page.

WHY. The 2026-10-21 redesign (John) gave the site three doors: Housing (the home page: the pipeline story), Berkeley
(the city: the Snapshot, Berkeley 2050, the maps) and Learn (the curriculum, data journalism, methods). A menu that is
hand-copied into twenty pages drifts; this writes ONE block, between markers, right after <body>, the same idempotent
way scripts/site_meta.py writes the head. Pages regenerated by their own builders (the Snapshot, Players, Pipeline
State, the Audit) lose it on a rebuild, so re-run this after them; scripts/deploy_gate.py refuses a page in PAGES
without the block.

Full-screen pages (the maps, map.html, the tours page) are left out on purpose: a bar above a 100vh map pushes it
off-screen. The menu is position: static except on the three section pages, where it sticks. The menu still LINKS to
the tours page (John, 2026-10-24: it was reachable only from a sentence inside the home page's Fly-through tab).

  .venv/bin/python scripts/site_nav.py
"""
import pathlib
import re

DOCS = pathlib.Path(__file__).resolve().parents[1] / "docs"
BEGIN, END = "<!-- BEGIN site_nav (generated by scripts/site_nav.py — do not hand-edit) -->", "<!-- END site_nav -->"
# page -> which door it belongs to
PAGES = {
    "index.html": "Housing", "explorer.html": "Housing", "pipeline-state.html": "Housing", "housing-audit.html": "Housing",
    "players.html": "Housing", "players-notes/index.html": "Housing", "mayor-briefing-2026-07.html": "Housing",
    "driving_survey_log.html": "Housing",
    "berkeley.html": "Berkeley", "berkeley-snapshot-2026-10.html": "Berkeley", "berkeley2050/index.html": "Berkeley",
    "learn.html": "Learn", "data-science-curriculum.html": "Learn", "reporters.html": "Learn",
    "reporters-local-models.html": "Learn", "methodology.html": "Learn", "technical-archive-2026.html": "Learn",
    "possibility-lab-test.html": "Learn",
}
STICKY = {"index.html", "berkeley.html", "learn.html"}
LEGACY_NAV = re.compile(r'<nav class="bb-nav".*?</nav>\n?', re.S)   # the composer's first copy, before markers existed


def block(page, door):
    up = "../" * page.count("/")
    items = [("Housing", up or "./"), ("Berkeley", f"{up}berkeley.html"), ("Learn", f"{up}learn.html"),
             ("Tours", f"{up}tours/")]
    links = "".join(f'<a class="m" href="{h}"{" aria-current=page" if n == door else ""}>{n}</a>' for n, h in items)
    pos = "sticky" if page in STICKY else "static"
    return f"""{BEGIN}
<style>
  .bb-nav {{ position: {pos}; top: 0; z-index: 1000; background: rgba(255,255,255,.97); border-bottom: 1px solid #e2e8f0;
            font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; line-height: 1.4; }}
  .bb-nav .in {{ max-width: 1000px; margin: 0 auto; padding: .55rem 1.25rem; display: flex; align-items: center; gap: 1.1rem;
                box-sizing: border-box; }}
  .bb-nav .logo {{ font-weight: 900; color: #1a365d; text-decoration: none; font-size: 1.1rem; margin-right: auto; letter-spacing: -.01em; }}
  .bb-nav .logo span {{ color: #d69e2e; }}
  .bb-nav a.m {{ color: #4a5568; text-decoration: none; font-weight: 700; font-size: .98rem; padding: .3rem 0; border-bottom: 3px solid transparent; }}
  .bb-nav a.m[aria-current=page] {{ color: #1a365d; border-bottom-color: #ffd166; }}
  .bb-nav a.m:hover {{ color: #1a365d; }}
  @media (max-width: 480px) {{ .bb-nav .in {{ gap: .75rem; padding: .55rem .9rem; }} .bb-nav .logo {{ font-size: 1rem; }}
                              .bb-nav a.m {{ font-size: .9rem; }} }}
  @media (max-width: 360px) {{ .bb-nav .in {{ gap: .45rem; padding: .5rem .5rem; }} .bb-nav .logo {{ font-size: .85rem; }}
                              .bb-nav a.m {{ font-size: .8rem; }} }}
</style>
<nav class="bb-nav" aria-label="BerkeleyBuild"><div class="in"><a class="logo" href="{up or './'}">Berkeley<span>Build</span></a>{links}</div></nav>
{END}
"""


def main():
    n = 0
    for page, door in PAGES.items():
        f = DOCS / page
        h = f.read_text(encoding="utf-8")
        new = block(page, door)
        if BEGIN in h:
            h = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda _: new, h, count=1, flags=re.S)
        else:
            h = LEGACY_NAV.sub("", h, count=1)
            m = re.search(r"<body[^>]*>\n?", h)
            assert m, f"{page}: no <body>"
            h = h[:m.end()] + new + h[m.end():]
        f.write_text(h, encoding="utf-8")
        n += 1
    print(f"site_nav: menu written into {n} page(s)")


if __name__ == "__main__":
    main()
