# The six lines a label can carry, and the row field each one needs. This mapping IS the subject of
# the notebook: it is the editorial decision, written down.
LINE_FIELDS = {
    'address':   'address_display',
    'units':     'total_units',
    'status':    'status_label',
    'storeys':   'height_stories',
    'height':    'height_feet',
    'filed':     'filed_date',
    'architect': 'architect',
    'developer': 'developer',
    'owner':     'owner_current',
}
# Projects whose labels we pin, so a silent content change is caught. Looked up by the address canon
# (v4_source.akey), because v4 can hold several projects at one address and resolves them explicitly.
ANCHORS = ['2128 Oxford St', '1974 SHATTUCK Ave', '2700 SHATTUCK Ave']
# Fields whose text is a NAME on the label. The publishing rule: organisations named, private
# individuals never. housing_rules.owner_name.is_organisation is the test.
NAME_FIELDS = ('architect', 'developer', 'owner_current')


def redact(lines, r, is_org):
    """Replace any label NAME the canon does not call an organisation with 'individual' -- for text that
    is STORED (baseline) or PRINTED (notebook). The sha is always taken on the true lines."""
    out = []
    for ln in lines:
        for f in NAME_FIELDS:
            v = r.get(f)
            if v and not is_org(v):
                for frag in {str(v)[:34], str(v)[:38], str(v)[:40], str(v)}:
                    ln = ln.replace(frag, 'individual')
        out.append(ln)
    return out


def v4_sha():
    h = hashlib.sha256()
    with open(V4, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()[:16]


# ==================================================== DERIVATIONS (the live truth)
def derive():
    """Field coverage across the live pipeline, plus a content hash per anchor label.

    Nothing here is a constant. Coverage is counted from gen_svg_labels.rows() -- the pipeline's own
    row source -- and the anchor hashes are taken from the SAME lines_for() the tour builder uses, so
    a change to the label's wording or to the underlying data both move the hash and both trip the gate.
    """
    import gen_svg_labels as G
    from scripts.tours import v4_source as V
    from housing_rules.owner_name import is_organisation
    d = {'n_projects': 0, 'coverage': {}, 'lines_filled': {}, 'anchors': {}, 'names_not_organisation': {}}
    os.chdir(ROOT)
    rows = G.rows(False)
    d['n_projects'] = len(rows)
    for name, col in LINE_FIELDS.items():
        d['coverage'][name] = sum(
            1 for r in rows
            if r[col] is not None and str(r[col]).strip() not in ('', '0', 'None'))
    hist = {}
    for r in rows:
        n = len([x for x in G.lines_for(r) if x])
        hist[n] = hist.get(n, 0) + 1
    d['lines_filled'] = {str(k): v for k, v in sorted(hist.items())}
    # the publishing-rule check: how many label NAMES the canon does not call an organisation
    for f in NAME_FIELDS:
        d['names_not_organisation'][f] = sum(1 for r in rows if r[f] and not is_organisation(r[f]))
    by_key = {r['akey']: r for r in rows}
    for a in ANCHORS:
        r = by_key.get(V.akey(a))
        if r is None:
            d['anchors'][a] = None
            continue
        lines = [x for x in G.lines_for(r) if x]
        d['anchors'][a] = {
            'project_key': r['project_key'],
            'lines': redact(lines, r, is_organisation),     # stored/printed text never carries an individual
            'sha': hashlib.sha256('\n'.join(lines).encode()).hexdigest()[:16],
        }
    return d, v4_sha()


# ==================================================== GATE (derived vs external baseline)
def _load(p):
    return json.load(open(p))


def newest_baseline(v4_only=True, d=None):
    hits = sorted(glob.glob(os.path.join(d or BASELINE_DIR, BASELINE_PATTERN)))
    hits = [h for h in hits if (_load(h).get('db') == 'v4') == v4_only]
    return hits[-1] if hits else None


def crosswalk(d):
    """v2-era baseline -> v4 derivation. A different database and a different row unit (v2: one row per
    unmerged project; v4: one row per address resolving to one project), so this is NOT a drift check."""
    p = newest_baseline(v4_only=False, d=LEGACY_DIR)
    if not p:
        return
    b = _load(p)
    print(f'  crosswalk (not a gate): v2-era {os.path.basename(p)} -> v4')
    print(f'    n_projects            {b.get("n_projects")!s:>6} -> {d["n_projects"]}')
    for name in LINE_FIELDS:
        print(f'    coverage[{name:9}]  {b.get("coverage", {}).get(name)!s:>6} -> {d["coverage"][name]}')
    for a in ANCHORS:
        print(f'    anchor {a}:\n      v2: {(b.get("anchors", {}).get(a) or {}).get("lines")}\n      v4: {(d["anchors"].get(a) or {}).get("lines")}')


def gate(d, sha, path):
    """Compare derived to the baseline. On mismatch DIAGNOSE and HALT -- both directions."""
    if path is None:
        print('  NO v4-ERA BASELINE — review the crosswalk above; append one with --write-baseline (John\'s call).')
        return False
    b = _load(path)
    print(f'  gating against {os.path.basename(path)}  (v4_sha then {b.get("v4_sha")}, now {sha})')
    bad = []
    if d['n_projects'] != b.get('n_projects'):
        bad.append(f'n_projects: computed {d["n_projects"]}, baseline {b.get("n_projects")}')
    for name, n in d['coverage'].items():
        if n != b.get('coverage', {}).get(name):
            bad.append(f'coverage[{name}]: computed {n}, baseline {b.get("coverage", {}).get(name)}')
    for f, n in d['names_not_organisation'].items():
        if n != b.get('names_not_organisation', {}).get(f):
            bad.append(f'names_not_organisation[{f}]: computed {n}, baseline {b.get("names_not_organisation", {}).get(f)}')
    for a, v in d['anchors'].items():
        bv = b.get('anchors', {}).get(a)
        if (v or {}).get('sha') != (bv or {}).get('sha'):
            bad.append(f'anchor[{a}]: sha computed {(v or {}).get("sha")}, baseline '
                       f'{(bv or {}).get("sha")}\n      now      : {(v or {}).get("lines")}'
                       f'\n      baseline : {(bv or {}).get("lines")}')
    if bad:
        print('\n  GATE FAILED — derived does not match the baseline:')
        for x in bad:
            print(f'    - {x}')
        print('\n  Likely causes, in order: (a) a v4 rebuild changed a project — if the new value is '
              'CORRECT, append a new baseline, never edit this logic; (b) lines_for() or v4_source was '
              'edited, which is an editorial change and needs a new baseline too; (c) an address became '
              'ambiguous or resolved in v4_source.by_address, which moves n_projects.')
        return False
    print('  GATE PASSED — every coverage count and anchor label matches the baseline.')
    return True


def write_baseline(d, sha):
    p = os.path.join(BASELINE_DIR, f'label_fields_baseline_{datetime.date.today().isoformat()}_v4.json')
    assert not os.path.exists(p), f'{p} exists — baselines are append-only'
    out = dict(d)
    out['db'] = 'v4'
    out['v4_sha'] = sha
    out['written_at'] = datetime.datetime.now().isoformat(timespec='seconds')
    legacy = newest_baseline(v4_only=False, d=LEGACY_DIR)
    out['supersedes_v2_era'] = os.path.basename(legacy) if legacy else None
    out['provenance'] = ('Derived by scripts/v4/build_jn_n.py from gen_svg_labels.rows() (v4 via '
                         'scripts/tours/v4_source.address_rows) and gen_svg_labels.lines_for().')
    json.dump(out, open(p, 'w'), indent=2)
    print(f'  wrote {p}')
    return p


