#!/usr/bin/env python3
"""pipeline_animation.py -- the home page's "Play Berkeley's whole housing pipeline" block, GENERATED, never hand-edited.

Every private project as a waffle (one square = 10 homes), month by month from January 2018, with a stacked history
of the pipeline stages (green on top = completed in the previous 12 months) and a 12-month completions bar strip.
Prototyped in scratch/2026-10-20_pipeline_viz/ and approved by John 2026-10-20.

READ-ONLY. Inputs, the same ones the site uses:
  docs/explorer_data.js   which projects count (UC excluded), their units and today's stage (the in_pipeline flag)
  v4 v_projects           the dates a project reached each stage (filed, entitled, building permit, completion)
  v4 inspections          the first inspection under a project's permits = construction start (the export's signal)
  v4 v_project_timeline   for projects that LEFT the pipeline: their last recorded event, used as the leaving date
                          (the City rarely records a withdrawal date)
Writes ONE marked block of docs/index.html, right after the ANCHOR comment (below the "Fly through Berkeley's future"
link; John 2026-10-20 moved it up from under the yearly table). Moving the anchor moves the block:

    <!-- BEGIN pipeline_animation data="<Explorer Generated stamp>" v4="<v4 sha16>" (generated by ...) -->
    ...
    <!-- END pipeline_animation -->

GATES: refuses to write unless the last frame equals today's stage totals in the Explorer data (so the animation can
never end on a number the site does not show); scripts/deploy_gate.py refuses a deploy whose block stamp differs from
the served Explorer data. Re-run after every export promotion, with site_numbers.py.

Run:  .venv/bin/python scripts/viz/pipeline_animation.py
"""
import datetime as dt
import html
import json
import os
import re
import sqlite3
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.v4 import stage_methods as SM  # noqa: E402

DATA = ROOT / "docs/explorer_data.js"
PAGE = ROOT / "docs/index.html"
TEMPLATE = Path(__file__).with_name("pipeline_animation_template.html")
START = (2018, 1)            # John 2026-10-20: the first year permits, completions and Planning records are all covered
CYCLE6 = "2022-06-30"        # 6th-cycle RHNA credit: first building permit on/after this date (generate_apr_v4.py)
BLOCK_RE = re.compile(r'<!-- BEGIN pipeline_animation.*?-->.*?<!-- END pipeline_animation -->', re.S)
ANCHOR = '<!-- ANCHOR pipeline_animation: scripts/viz/pipeline_animation.py writes its block right after this line -->'
STAGE_OF = {"Pre-Application": "preapp", "Under Review": "review", "Entitled": "entitled",
            "Entitled but Inactive": "stalled", "Completed": "completed", "Withdrawn": "left", "Denied": "left",
            "Expired": "left", "Permitted, Not Started": "permitted", "Permitted but Inactive": "permitted",
            "Building Permits Filed": "permitted"}    # everything else (Under Construction, Construction Quiet) = building
ORDER = ("preapp", "review", "entitled", "stalled", "permitted", "building", "completed", "left")


def month_index(d, last):
    if not d:
        return None
    y, m = int(d[:4]), int(d[5:7])
    return min((y - START[0]) * 12 + (m - START[1]), last)    # negative = before the first frame (keeps true ages)


def day(d):
    """days since START, for the inactive rule (the export compares DATES, so the animation must too)"""
    return (dt.date.fromisoformat(d[:10]) - dt.date(START[0], START[1], 1)).days if d else None


def frame_day(i, last, today_day):
    """the day a frame stands for: the last day of its month; the last frame is today"""
    if i >= last:
        return today_day
    y, m = START[0] + (START[1] - 1 + i + 1) // 12, (START[1] - 1 + i + 1) % 12 + 1
    return (dt.date(y, m, 1) - dt.date(START[0], START[1], 1)).days - 1


def stage_at(r, i, last, today_day):
    """The SAME rule as the page's stageAt() -- keep the two in step."""
    first, ent, bp, co, out, u, pre, ins, act, entd = r
    if first is None or first > i:
        return None
    if out is not None and out <= i:
        return "left"
    if co is not None and co <= i:
        return "completed"
    if bp is not None and bp <= i:
        return "building" if ins is not None and ins <= i else "permitted"
    if ent is not None and ent <= i:
        # inactive = approved 36+ months ago AND no activity on the project's own records in the last 36 months (the
        # export's rule, John 2026-10-20); act = the months with any recorded event on the project's records
        T = frame_day(i, last, today_day)
        recent = max((a for a in act if a <= T), default=None)
        return "stalled" if T - entd > 1095 and (recent is None or T - recent > 1095) else "entitled"
    return "preapp" if pre else "review"


def payload():
    t = DATA.read_text()
    stamp = re.search(r"Generated:\s*(.+)", t).group(1).strip()
    ex = json.loads(t[t.index("{"):t.rindex("}") + 1])
    P = {p["id"]: p for p in ex["projects"] if not p.get("is_uc_project")}
    assert all("in_pipeline" in p for p in P.values()), "Explorer data predates the in_pipeline flag: re-export first"
    uc_beds = sum(p.get("beds") or 0 for p in ex["projects"] if p.get("is_uc_project") and p["status"] != "Completed")

    db = SM.ro(SM.LIVE)
    v = {r[0]: r[1:] for r in db.execute("SELECT project_key, status, anchor_role, filed_date, accepted_date, entitled_date, "
                                         "bp_issued_date, co_issued_date, completed_year_reported FROM v_projects")}
    first_ev = dict(db.execute("SELECT project_key, MIN(event_date) FROM v_project_timeline GROUP BY project_key"))
    act_months = {}
    for k, d in db.execute("SELECT DISTINCT project_key, substr(event_date, 1, 10) FROM v_project_timeline WHERE event_date IS NOT NULL"):
        act_months.setdefault(k, set()).add(d)
    last_ev = dict(db.execute("SELECT project_key, MAX(event_date) FROM v_project_timeline GROUP BY project_key"))
    first_insp = dict(db.execute("""SELECT json_extract(p.notes, '$.project_key'), MIN(e.event_date) FROM projects p
        JOIN project_structures ps USING(project_id) JOIN structure_events se USING(structure_id) JOIN events e USING(event_id)
        WHERE e.event_type_code = 'inspection' GROUP BY 1"""))
    # completions are complete only inside the CPRA feed: its last finaled new-unit master permit (the date the home
    # page's yearly table states, site_numbers.py)
    feed_end = db.execute("""SELECT MAX(e.event_date) FROM events e JOIN event_classifications c USING(event_id)
        WHERE e.event_type_code='permit_finaled' AND c.housing_role='new_unit' AND c.is_master=1
        AND COALESCE(c.net_units,0)>0""").fetchone()[0]
    today = dt.date.today()
    last = (today.year - START[0]) * 12 + (today.month - START[1])
    f = lambda d: month_index(d, last)

    rows, notes = [], Counter()
    for k, p in P.items():
        st, role, filed, acc, ent, bp, co, cy = v[k]
        if p["status"] == "Completed" and not any((filed, acc, ent, bp, co)):
            co = f"{cy}-01-01" if cy else f"{START[0]}-01-01"     # the historic ledger: completed before the records
            notes["historic"] += 1
        if p["status"] == "Completed" and not co:
            co = bp or ent or filed                                # no CO date on record: finished at its last stage
            notes["completed without a CO date"] += 1
        dates = [d for d in (filed, acc, ent, bp, co) if d]
        first = min(dates) if dates else None
        out = last_ev.get(k) if p["left_pipeline"] else None
        if not first:
            first = first_ev.get(k) or out
            notes["no stage date (first seen at its earliest event)"] += 1
        if st in ("under_construction", "stale") and not bp:
            bp = ent or filed or first                             # building with no permit date: permitted when last dated
            notes["building without a permit date"] += 1
        ins = first_insp.get(k)
        if bp and co and not ins:
            ins = bp                                               # finished with no inspection on record: started at permit
            notes["completed without inspections"] += 1
        act = sorted({day(d) for d in act_months.get(k, ()) if d >= ent}) if ent else []   # event days from the approval on
        rows.append([f(first), f(ent), f(bp), f(co), f(out), int(p["units"] or 0), 1 if role == "pre_application" else 0, f(ins),
                     act, day(ent)])

    today_day = (today - dt.date(START[0], START[1], 1)).days
    got, want = Counter(), Counter()
    for r in rows:
        s = stage_at(r, last, last, today_day)
        if s:
            got[s] += r[5]
    for p in P.values():
        want[STAGE_OF.get(p["status"], "building")] += int(p["units"] or 0)
    print("final frame vs Explorer data (units):")
    for g in ORDER:
        print(f"  {g:10} {got[g]:>6,}  {want[g]:>6,}  {'OK' if got[g] == want[g] else 'DIFF'}")
    for n, c in notes.items():
        print(f"  note: {c} {n}")
    bad = [g for g in ORDER if got[g] != want[g]]
    if bad:
        raise SystemExit(f"REFUSED: the last frame differs from the Explorer data in {bad} -- nothing written")
    return stamp, {"rows": rows, "start": START, "last": last, "stamp": stamp[:10], "uc_beds": uc_beds,
                   "cycle6": month_index(CYCLE6, last) + 1, "co_end": month_index(feed_end, last), "feed_end": feed_end,
                   "n_historic": notes["historic"],
                   "today_day": today_day, "frame_days": [frame_day(i, last, today_day) for i in range(last + 1)]}


def main():
    stamp, data = payload()
    sha = SM._sha256(SM.LIVE)[:16]
    body = TEMPLATE.read_text().replace("__DATA__", json.dumps(data, separators=(",", ":")))
    block = (f'<!-- BEGIN pipeline_animation data="{html.escape(stamp)}" v4="{sha}" '
             f'(generated by scripts/viz/pipeline_animation.py — do not hand-edit) -->\n{body}<!-- END pipeline_animation -->')
    page = BLOCK_RE.sub("", PAGE.read_text())                      # wherever it was, it goes after the anchor
    assert page.count(ANCHOR) == 1, f"anchor {ANCHOR!r} not found exactly once in {PAGE}"
    page = page.replace(ANCHOR, ANCHOR + "\n" + block, 1)
    PAGE.write_text(page)
    print(f"pipeline_animation: {len(data['rows']):,} projects, {len(block):,} bytes, explorer {stamp}, v4 {sha}")


if __name__ == "__main__":
    main()
